"""Turn the NLP-KG fields-of-study OWL file into the JSON the app bundles.

The vocabulary behind concept anchoring (``nlp_pillars/vocabulary.py``) is the
NLP-KG "NLP Fields of Study" hierarchy (Schopf & Matthes, ACL 2024 demo;
https://github.com/NLP-Knowledge-Graph/NLP-KG-WebApp, MIT licence). The OWL
file is 760 KB of XML; the app needs only each field's label, synonyms,
description, depth and parent. This script keeps exactly that, so the bundled
file is small, diff-able and regenerated by one command::

    gh api repos/NLP-Knowledge-Graph/NLP-KG-WebApp/contents/NLP-FoS-Hierarchy.owl \\
        -H 'Accept: application/vnd.github.raw' > /tmp/fos/NLP-FoS-Hierarchy.owl
    python scripts/build_nlp_kg_vocabulary.py /tmp/fos/NLP-FoS-Hierarchy.owl \\
        nlp_pillars/vocab/nlp_kg_fields.json --source-ref <commit sha>

Stdlib only. Nothing is fetched here.
"""

from __future__ import annotations

import argparse
import json
import sys
import xml.etree.ElementTree as ET
from pathlib import Path
from urllib.parse import unquote

OWL = "{http://www.w3.org/2002/07/owl#}"
RDF = "{http://www.w3.org/1999/02/22-rdf-syntax-ns#}"

LICENCE = "MIT"
SOURCE_URL = "https://github.com/NLP-Knowledge-Graph/NLP-KG-WebApp"


def fragment(iri: str) -> str:
    """The id of an IRI: what follows ``#``."""
    return unquote(iri.rsplit("#", 1)[-1])


def children(element: ET.Element, local: str) -> list[ET.Element]:
    """Child elements called ``local`` in any namespace.

    The file spreads a field's properties over the taxonomy and hierarchy
    namespaces (``subFieldOf`` is one, ``usedFor`` the other); the local name
    is what is stable.
    """
    return [child for child in element if child.tag.rsplit("}", 1)[-1] == local]


def humanise(identifier: str) -> str:
    """A label for a field the OWL file did not label."""
    return identifier.replace("_&_", " & ").replace("_", " ").strip()


def parse(owl_path: Path) -> list[dict]:
    """Every field of study, sorted by id, with its parents resolved to ids."""
    root = ET.parse(owl_path).getroot()
    fields: dict[str, dict] = {}
    for element in root.findall(OWL + "NamedIndividual"):
        iri = element.get(RDF + "about") or ""
        types = {fragment(t.get(RDF + "resource") or "") for t in children(element, "type")}
        if "FieldOfStudy" not in types:
            continue
        identifier = fragment(iri)
        label = None
        for node in children(element, "label"):
            label = (node.text or "").strip() or label
        description = None
        for node in children(element, "description"):
            description = " ".join((node.text or "").split()) or description
        level = None
        for node in children(element, "level"):
            try:
                level = int((node.text or "").strip())
            except ValueError:
                pass
        parents = sorted(
            {
                fragment(node.get(RDF + "resource") or "")
                for node in children(element, "subFieldOf")
                if node.get(RDF + "resource")
            }
        )
        synonyms = sorted(
            {
                (node.text or "").strip()
                for node in children(element, "hasSynonym")
                if (node.text or "").strip()
            }
        )
        fields[identifier] = {
            "id": identifier,
            "label": label or humanise(identifier),
            "synonyms": synonyms,
            "description": description or "",
            "level": level,
            "parents": parents,
        }
    # A parent that is not itself a field (the taxonomy root) is dropped.
    for row in fields.values():
        row["parents"] = [parent for parent in row["parents"] if parent in fields]
    return [fields[key] for key in sorted(fields)]


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    parser.add_argument("owl", type=Path)
    parser.add_argument("out", type=Path)
    parser.add_argument("--source-ref", default="unknown", help="commit sha of the OWL file")
    args = parser.parse_args(argv)

    fields = parse(args.owl)
    if not fields:
        print("no fields of study found; is this the NLP-FoS-Hierarchy.owl file?", file=sys.stderr)
        return 1
    document = {
        "vocabulary": "nlp-kg",
        "name": "NLP-KG fields of study",
        "licence": LICENCE,
        "source": SOURCE_URL,
        "source_ref": args.source_ref,
        "citation": "Schopf & Matthes, NLP-KG: A System for Exploratory Search of "
        "Scientific Literature in Natural Language Processing, ACL 2024 demo.",
        "fields": fields,
    }
    args.out.parent.mkdir(parents=True, exist_ok=True)
    args.out.write_text(
        json.dumps(document, indent=1, ensure_ascii=False, sort_keys=True) + "\n",
        encoding="utf-8",
    )
    synonyms = sum(len(row["synonyms"]) for row in fields)
    print(f"{len(fields)} fields, {synonyms} synonyms -> {args.out}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
