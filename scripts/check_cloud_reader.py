#!/usr/bin/env python3
"""Fail if the cloud reader gains a way to call AI or an outside service.

The reader (cloud/reader/) is a read-only copy of the library on Cloudflare.
Its promise (cloud-reader plan, section 7) is that the cloud has no path to
generation, keys or spend. This script holds three parts of that promise:

  1. wrangler.toml declares exactly three bindings: DOCS (R2), REVIEWS (D1) and
     ASSETS (static files). Workers AI, Vectorize, queues, service bindings,
     KV, Durable Objects, Hyperdrive, extra environments and the like fail the
     build, as does a [vars] name nobody has listed here.
  2. The Worker source (cloud/reader/src) makes one outbound request: the
     team's Access key endpoint in certs.js. Any other fetch, socket, dynamic
     import, eval or non-relative import fails, and so does a URL literal that
     is not https://${teamDomain}.
  3. The page (cloud/reader/public, minus the generated static/ copy) reaches no
     other origin: no absolute URL, no WebSocket, XHR, EventSource or beacon.
     The Worker's CSP must keep connect-src 'self' and carry no wildcard.

It is a tripwire, not a proof. A determined author can hide a call from a
scanner; the boundary that holds is the binding list and the CSP, and this
guards both. Raising the bar means a person edits the allow-lists below, in a
diff a reviewer reads. Stdlib only, like check_bare_slugs.py, so the CI job
finishes in seconds and runs even when the dependency install is broken.

Usage:
    python scripts/check_cloud_reader.py [--root DIR]    # DIR defaults to the repo root

Exit status is 1 if anything is found, so it can gate CI.
"""

from __future__ import annotations

import argparse
import pathlib
import re
import sys
import tomllib

READER = pathlib.Path("cloud") / "reader"

# --- wrangler.toml ---------------------------------------------------------

ALLOWED_TOP_LEVEL_KEYS = {
    "name",
    "main",
    "compatibility_date",
    "workers_dev",
    "preview_urls",
    "routes",
    "observability",
    "assets",
    "r2_buckets",
    "d1_databases",
    "vars",
}
ALLOWED_R2 = {"DOCS"}
ALLOWED_D1 = {"REVIEWS"}
ALLOWED_ASSETS = "ASSETS"
# Plain-text config and the names of secrets the Worker reads. A model key does
# not belong in this list, which is the point of listing it.
ALLOWED_VARS = {
    "TEAM_DOMAIN",
    "ACCESS_AUD",
    "INGEST_AUD",
    "INGEST_SERVICE_TOKENS",
    "INGEST_MAX_BYTES",
    "ALLOWED_EMAILS",
    "ALLOWED_SERVICE_TOKENS",
}
# Config files: the deployed one, and the throwaway one the dev smoke test uses.
WRANGLER_FILES = (READER / "wrangler.toml", READER / "test" / "wrangler.smoke.toml")

# --- Worker source ---------------------------------------------------------

WORKER_SRC = READER / "src"
WORKER_SUFFIXES = {".js", ".mjs", ".ts"}
# The only file that may touch the global fetch, and the only receiver other
# code may call `.fetch` on (the static-assets binding).
FETCH_FILE = "certs.js"
FETCH_RECEIVERS = {"env.ASSETS"}
SUSPECT_NAMES = (
    "XMLHttpRequest",
    "WebSocket",
    "WebSocketPair",
    "EventSource",
    "WebTransport",
    "sendBeacon",
    "importScripts",
)

# --- Page ------------------------------------------------------------------

PAGE_DIR = READER / "public"
# public/static/ is generated by build-assets.sh from webui/static and is not committed.
PAGE_SKIP = {PAGE_DIR / "static"}
PAGE_SUFFIXES = {".js", ".mjs", ".html", ".css"}
# An XML namespace, never fetched.
PAGE_URL_OK = ("http://www.w3.org/2000/svg",)
# importScripts is allowed on the page only for the reader's own files: every
# argument a root-relative string literal ('/x.js', never '//host/x.js').
IMPORT_SCRIPTS_OK_RE = re.compile(
    r"""importScripts\s*\(\s*'/(?!/)[^'\s]*'(?:\s*,\s*'/(?!/)[^'\s]*')*\s*,?\s*\)"""
)

URL_RE = re.compile(r"https?://", re.I)


Problem = tuple[str, int, str]  # (path, line, message)


# ---------------------------------------------------------------------------
# A small JavaScript scrubber. Regexes over raw source would trip on a URL in a
# comment or a word in an error message, so first split the file into
#   code_keep  - comments blanked, string and template text kept (to read URLs
#                and import specifiers)
#   code_blank - comments and string/template text blanked (to find real code)
# Both are the same length as the source and keep newlines, so offsets and
# line numbers agree.
# ---------------------------------------------------------------------------

_REGEX_AFTER = set("(,=:[!&|?{};+-*%<>~^")
_REGEX_AFTER_WORDS = {"return", "typeof", "case", "in", "of", "void", "delete", "throw", "await", "yield"}


def scrub_js(src: str) -> tuple[str, str]:
    keep: list[str] = []
    blank: list[str] = []
    n = len(src)
    i = 0
    # One counter per open `${`: how many `{` are open inside it.
    tpl_depth: list[int] = []

    def emit(text: str, keep_text: bool, blank_text: bool) -> None:
        keep.append(text if keep_text else re.sub(r"[^\n]", " ", text))
        blank.append(text if blank_text else re.sub(r"[^\n]", " ", text))

    def prev_significant() -> str:
        code = "".join(blank)
        j = len(code) - 1
        while j >= 0 and code[j].isspace():
            j -= 1
        if j < 0:
            return ""
        if code[j].isalnum() or code[j] in "_$":
            k = j
            while k >= 0 and (code[k].isalnum() or code[k] in "_$"):
                k -= 1
            return code[k + 1 : j + 1]
        return code[j]

    def read_template(start: int) -> int:
        """Consume template text from `start` up to the closing backtick or a `${`."""
        j = start
        while j < n:
            ch = src[j]
            if ch == "\\":
                j += 2
            elif ch == "`":
                emit(src[start:j], True, False)
                emit("`", True, True)
                return j + 1
            elif ch == "$" and src[j + 1 : j + 2] == "{":
                emit(src[start:j], True, False)
                emit("${", True, True)
                tpl_depth.append(0)
                return j + 2
            else:
                j += 1
        emit(src[start:], True, False)
        return n

    while i < n:
        ch = src[i]
        two = src[i : i + 2]
        if two == "//":
            j = src.find("\n", i)
            j = n if j < 0 else j
            emit(src[i:j], False, False)
            i = j
        elif two == "/*":
            j = src.find("*/", i + 2)
            j = n if j < 0 else j + 2
            emit(src[i:j], False, False)
            i = j
        elif ch in "'\"":
            j = i + 1
            while j < n and src[j] != ch and src[j] != "\n":
                j += 2 if src[j] == "\\" else 1
            j = min(j, n - 1)
            emit(ch, True, True)
            emit(src[i + 1 : j], True, False)
            emit(src[j : j + 1], True, True)
            i = j + 1
        elif ch == "`":
            emit("`", True, True)
            i = read_template(i + 1)
        elif ch == "/" and (prev_significant() in _REGEX_AFTER or prev_significant() in _REGEX_AFTER_WORDS or not prev_significant()):
            j, in_class = i + 1, False
            while j < n and src[j] != "\n":
                if src[j] == "\\":
                    j += 2
                    continue
                if src[j] == "[":
                    in_class = True
                elif src[j] == "]":
                    in_class = False
                elif src[j] == "/" and not in_class:
                    break
                j += 1
            emit("/", True, True)
            emit(src[i + 1 : j], True, False)
            emit(src[j : j + 1], True, True)
            i = j + 1
        elif ch == "{" and tpl_depth:
            tpl_depth[-1] += 1
            emit(ch, True, True)
            i += 1
        elif ch == "}" and tpl_depth:
            if tpl_depth[-1] == 0:
                tpl_depth.pop()
                emit("}", True, True)
                i = read_template(i + 1)
            else:
                tpl_depth[-1] -= 1
                emit(ch, True, True)
                i += 1
        else:
            emit(ch, True, True)
            i += 1
    return "".join(keep), "".join(blank)


def _line(text: str, offset: int) -> int:
    return text.count("\n", 0, offset) + 1


# ---------------------------------------------------------------------------
# Checks
# ---------------------------------------------------------------------------


def check_wrangler(root: pathlib.Path, rel: pathlib.Path) -> list[Problem]:
    path = root / rel
    name = rel.as_posix()
    try:
        config = tomllib.loads(path.read_text(encoding="utf-8"))
    except FileNotFoundError:
        return [(name, 1, "file is missing; the guard cannot vouch for a Worker it cannot read")]
    except (OSError, UnicodeDecodeError, tomllib.TOMLDecodeError) as exc:
        return [(name, 1, f"could not read as TOML ({exc})")]

    problems: list[Problem] = []

    def bad(message: str) -> None:
        problems.append((name, 1, message))

    for key in sorted(set(config) - ALLOWED_TOP_LEVEL_KEYS):
        bad(
            f"`{key}` is not allowed. The reader's bindings are DOCS (R2), REVIEWS (D1) and "
            f"ASSETS; AI, Vectorize, queues, service bindings, KV, Durable Objects and extra "
            f"environments are how the cloud would gain a path to generation or spend"
        )

    for key in ("workers_dev", "preview_urls"):
        if config.get(key) is True:
            bad(f"`{key} = true` makes a URL that skips Cloudflare Access")

    assets = config.get("assets")
    if assets is not None and assets.get("binding") != ALLOWED_ASSETS:
        bad(f"[assets] binding must be {ALLOWED_ASSETS}")

    for table, allowed in (("r2_buckets", ALLOWED_R2), ("d1_databases", ALLOWED_D1)):
        for entry in config.get(table) or []:
            if entry.get("binding") not in allowed:
                bad(f"[[{table}]] binding {entry.get('binding')!r} is not one of {sorted(allowed)}")

    for var in sorted(set(config.get("vars") or {}) - ALLOWED_VARS):
        bad(f"[vars] {var} is not on the allow-list in scripts/check_cloud_reader.py")

    return problems


def check_worker_source(root: pathlib.Path) -> list[Problem]:
    src_dir = root / WORKER_SRC
    files = sorted(p for p in src_dir.rglob("*") if p.suffix in WORKER_SUFFIXES) if src_dir.is_dir() else []
    if not files:
        return [(WORKER_SRC.as_posix(), 1, "no Worker source found; the guard cannot vouch for it")]

    problems: list[Problem] = []
    for path in files:
        name = path.relative_to(root).as_posix()
        try:
            keep, blank = scrub_js(path.read_text(encoding="utf-8"))
        except (OSError, UnicodeDecodeError) as exc:
            problems.append((name, 1, f"could not read ({exc})"))
            continue

        def bad(offset: int, message: str) -> None:
            problems.append((name, _line(blank, offset), message))

        # fetch: a bare `fetch` is the global one; `x.fetch` is allowed only on
        # the static-assets binding.
        bare = [m for m in re.finditer(r"(?<![\w$.])fetch\b(?!\s*:)", blank)]
        if path.name == FETCH_FILE:
            # createKeyStore(teamDomain, fetchImpl = fetch): one reference, no call.
            if len(bare) != 1 or not re.search(r"fetchImpl\s*=\s*fetch\b", blank):
                for m in bare:
                    bad(m.start(), "global fetch is used in a way certs.js was not approved for")
            if len(re.findall(r"\bfetchImpl\s*\(", blank)) != 1:
                bad(0, "certs.js must call fetchImpl exactly once (the Access key endpoint)")
        else:
            for m in bare:
                bad(m.start(), "outbound fetch; only certs.js may fetch (the Access key endpoint)")
        for m in re.finditer(r"([\w$.]*)\s*\.\s*fetch\b", blank):
            if m.group(1) not in FETCH_RECEIVERS:
                bad(m.start(), f"`{m.group(1) or '?'}.fetch` is an outbound call; only env.ASSETS.fetch is allowed")

        for m in re.finditer(r"\b(" + "|".join(SUSPECT_NAMES) + r")\b", blank):
            bad(m.start(), f"`{m.group(1)}` opens a connection the reader does not need")
        for m in re.finditer(r"\beval\s*\(|\bnew\s+Function\b|\bimport\s*\(", blank):
            bad(m.start(), "dynamic code or dynamic import")

        for m in re.finditer(r"\b(?:from|import)\s*(['\"])", blank):
            start = m.end()
            spec = keep[start : keep.index(m.group(1), start)]
            if not spec.startswith(("./", "../")):
                bad(m.start(), f"import of {spec!r}; the Worker has no dependencies and imports only its own files")

        for m in URL_RE.finditer(keep):
            if not keep.startswith("${teamDomain}", m.end()):
                bad(m.start(), "URL literal; the only one allowed is https://${teamDomain} (Access issuer and key endpoint)")

        if path.name == "worker.js":
            if "connect-src 'self'" not in keep:
                bad(0, "the Content-Security-Policy must keep connect-src 'self'")
            if "default-src 'none'" not in keep:
                bad(0, "the Content-Security-Policy must keep default-src 'none'")
            for m in re.finditer(r"-src[^\n]*\*", keep):
                bad(m.start(), "wildcard in a CSP source list")
    return problems


def check_page(root: pathlib.Path) -> list[Problem]:
    page = root / PAGE_DIR
    if not page.is_dir():
        return [(PAGE_DIR.as_posix(), 1, "no page found; the guard cannot vouch for it")]
    problems: list[Problem] = []
    for path in sorted(page.rglob("*")):
        rel = path.relative_to(root)
        if path.suffix not in PAGE_SUFFIXES or any(skip in rel.parents for skip in PAGE_SKIP):
            continue
        name = rel.as_posix()
        try:
            text = path.read_text(encoding="utf-8")
        except (OSError, UnicodeDecodeError) as exc:
            problems.append((name, 1, f"could not read ({exc})"))
            continue
        if path.suffix in {".js", ".mjs"}:
            keep, blank = scrub_js(text)
        else:
            # HTML and CSS: drop comments, keep line numbers.
            pattern = r"<!--.*?-->" if path.suffix == ".html" else r"/\*.*?\*/"
            keep = blank = re.sub(pattern, lambda m: re.sub(r"[^\n]", " ", m.group(0)), text, flags=re.S)

        def bad(offset: int, message: str) -> None:
            problems.append((name, _line(keep, offset), message))

        for m in URL_RE.finditer(keep):
            if not any(keep.startswith(ok, m.start()) for ok in PAGE_URL_OK):
                bad(m.start(), "absolute URL; the page talks to its own origin only")
        for m in re.finditer(r"""(?:src|href|action|srcset|url\()\s*=?\s*['"]?\s*//""", keep):
            bad(m.start(), "protocol-relative URL; the page talks to its own origin only")
        if path.suffix in {".js", ".mjs"}:
            for m in re.finditer(r"\b(" + "|".join(SUSPECT_NAMES) + r")\b", blank):
                if m.group(1) == "importScripts" and IMPORT_SCRIPTS_OK_RE.match(keep, m.start()):
                    continue
                bad(m.start(), f"`{m.group(1)}` is not used by the reader")
            for m in re.finditer(r"""\bfetch\s*\(\s*(['"`])\s*//""", keep):
                bad(m.start(), "fetch of a protocol-relative URL")
            for m in re.finditer(r"\beval\s*\(|\bnew\s+Function\b", blank):
                bad(m.start(), "dynamic code")
    return problems


def run_checks(root: pathlib.Path) -> list[Problem]:
    problems: list[Problem] = []
    for rel in WRANGLER_FILES:
        problems += check_wrangler(root, rel)
    problems += check_worker_source(root)
    problems += check_page(root)
    return problems


def main(argv: list[str]) -> int:
    parser = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    parser.add_argument("--root", type=pathlib.Path, default=pathlib.Path(__file__).resolve().parent.parent)
    args = parser.parse_args(argv[1:])

    problems = run_checks(args.root)
    for name, line, message in problems:
        # GitHub Actions renders this form as an inline annotation.
        print(f"::error file={name},line={line}::{message}")
        print(f"{name}:{line}: {message}")
    if problems:
        print(
            f"\n{len(problems)} cloud reader violation(s). The reader must not gain a path to "
            f"AI, keys, spend or an outside service; see docs/cloud-reader.md.",
            file=sys.stderr,
        )
        return 1
    print("Cloud reader guard: bindings, Worker source and page are within the allowed set.")
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv))
