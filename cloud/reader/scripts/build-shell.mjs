// Write public/shell.js: the list of files the service worker precaches and a version that
// changes whenever any of them does. sw.js imports it, and the browser re-checks imported
// scripts when it looks for a new worker, so changing a page file ships a new shell.
//   node cloud/reader/scripts/build-shell.mjs        (build-assets.sh runs it)
import { createHash } from 'node:crypto';
import { readFileSync, readdirSync, statSync, writeFileSync } from 'node:fs';
import { join, relative, sep } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

// The worker and the files it imports are not part of what it caches.
const NOT_SHELL = new Set(['sw.js', 'sw-core.js', 'shell.js']);

/** `files` is `[{path: 'js/reader.js', bytes}]`, paths relative to public/. */
export function buildShell(files) {
  const entries = files
    .filter((f) => !NOT_SHELL.has(f.path) && !f.path.split('/').some((part) => part.startsWith('.')))
    .map((f) => ({ path: f.path === 'index.html' ? '/' : `/${f.path}`, sha: createHash('sha256').update(f.bytes).digest('hex') }))
    .sort((a, b) => (a.path < b.path ? -1 : 1));
  const version = createHash('sha256').update(entries.map((e) => `${e.path}\0${e.sha}\n`).join('')).digest('hex').slice(0, 12);
  return { version, files: entries.map((e) => e.path) };
}

function walk(dir) {
  return readdirSync(dir).flatMap((name) => {
    const full = join(dir, name);
    return statSync(full).isDirectory() ? walk(full) : [full];
  });
}

export function readPublic(dir) {
  return walk(dir).map((full) => ({ path: relative(dir, full).split(sep).join('/'), bytes: readFileSync(full) }));
}

export function shellScript(shell) {
  return `// Generated by scripts/build-shell.mjs. Do not edit; it is not committed.\nself.NLP_SHELL = ${JSON.stringify(shell)};\n`;
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  const publicDir = fileURLToPath(new URL('../public', import.meta.url));
  const shell = buildShell(readPublic(publicDir));
  if (!shell.files.includes('/') || !shell.files.includes('/js/reader.js')) {
    console.error('public/ has no index.html or js/reader.js: wrong directory?');
    process.exit(1);
  }
  writeFileSync(join(publicDir, 'shell.js'), shellScript(shell));
  console.log(`public/shell.js: version ${shell.version}, ${shell.files.length} files`);
}
